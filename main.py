st.header("7. 제작 국가와 장르별 영화 편수 (선버스트)")

선버스트데이터 = df.dropna(
    subset=["nation", "장르", "movieNm"]
).copy()

# 제작 국가가 여러 개로 적혀 있는 경우 첫 번째 국가만 사용
선버스트데이터["제작국가"] = (
    선버스트데이터["nation"]
    .astype(str)
    .str.split("|")
    .str[0]
)

# 국가 → 장르별 영화 편수를 계산
국가장르편수 = (
    선버스트데이터
    .groupby(["제작국가", "장르"])
    .size()
    .reset_index(name="영화편수")
)

fig = px.sunburst(
    국가장르편수,
    path=["제작국가", "장르"],
    values="영화편수",
    labels={
        "제작국가": "제작 국가",
        "장르": "장르",
        "영화편수": "영화 편수"
    }
)

fig.update_traces(
    hovertemplate=
    "%{label}<br>"
    "영화 편수: %{value}편"
    "<extra></extra>"
)

st.plotly_chart(
    fig,
    use_container_width=True
)

st.text_input(
    "이 그래프로 알 수 있는 것",
    key="note7"
)


st.divider()


